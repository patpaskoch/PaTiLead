-- PaTiLead settings and marker logic. Run via PaTiAdmin/tools/check.sh.
local wow = require("wow_api")

local function load()
    return wow.loadAddonFile("Logic.lua", {}).Logic
end

describe("Logic.Migrate", function()
    it("creates defaults for a new character (no saved variables before)", function()
        local db = load().Migrate(nil)
        assert.same({ 8, 7, 5, 6, 4, 3, 2, 1 }, db.markers)
        assert.is_false(db.locked)
        assert.is_true(db.showPull)
        assert.equal("", db.note)
        assert.equal(1, db.schema)
    end)

    it("keeps saved values and replaces a broken marker list", function()
        local db = load().Migrate({ showPull = false, note = "Kara Montag", markers = { 8 }, x = 3 })
        assert.is_false(db.showPull)
        assert.equal("Kara Montag", db.note)
        assert.equal(8, #db.markers)
        assert.equal(3, db.x)
    end)
end)

describe("Logic.SetSlot", function()
    it("moves a marker instead of showing it twice", function()
        local Logic = load()
        local markers = Logic.SetSlot({ 8, 7, 5, 6, 4, 3, 2, 1 }, 1, 1)
        assert.same({ 1, 7, 5, 6, 4, 3, 2, 8 }, markers)
    end)

    it("can empty a slot", function()
        local Logic = load()
        local markers = Logic.SetSlot({ 8, 7, 5, 6, 4, 3, 2, 1 }, 2, 0)
        assert.same({ 8, 5, 6, 4, 3, 2, 1 }, Logic.VisibleMarkers(markers))
    end)
end)

describe("Logic.RestoreDefaults", function()
    it("keeps the note and the position", function()
        local db = load().RestoreDefaults({ note = "hi", x = 1, showPull = false, markers = { 1, 0, 0, 0, 0, 0, 0, 0 } })
        assert.equal("hi", db.note)
        assert.equal(1, db.x)
        assert.is_true(db.showPull)
        assert.same({ 8, 7, 5, 6, 4, 3, 2, 1 }, db.markers)
    end)
end)

describe("Logic helpers", function()
    it("builds the reset macro text: every marker to yourself, then clear", function()
        local text = load().ResetMacroText()
        assert.matches("^/tm %[@player%] 1\n", text)
        assert.matches("/tm %[@player%] 8\n/tm %[@player%] 0$", text)
    end)

    it("cleans the note: one line, at most 200 characters", function()
        local Logic = load()
        assert.equal("a b", Logic.CleanNote("a\nb"))
        assert.equal(200, #Logic.CleanNote(string.rep("x", 300)))
        assert.equal("", Logic.CleanNote(nil))
    end)

    it("counts roles", function()
        local counts = load().CountRoles({ "TANK", "HEALER", "DAMAGER", "DAMAGER", "NONE" })
        assert.same({ TANK = 1, HEALER = 1, DAMAGER = 2, NONE = 1 }, counts)
    end)
end)

describe("Secret-value order (readable check before any comparison)", function()
    -- A stand-in secret: ordering, arithmetic and concatenation raise an error. (Lua 5.1 cannot trap `== nil`,
    -- so the check-first order itself is guaranteed by the code, not proven by these tests.)
    local function trap() error("secret value was compared or used") end
    local secret = setmetatable({}, { __eq = trap, __lt = trap, __le = trap, __add = trap, __concat = trap })
    local isSecret = function(value) return rawequal(value, secret) end

    it("Readable returns nil for a secret and the value otherwise", function()
        local Logic = load()
        assert.is_nil(Logic.Readable(secret, isSecret))
        assert.is_true(Logic.Readable(true, isSecret))
        assert.is_false(Logic.Readable(false, isSecret))
    end)

    it("MarkerIndex returns nil for a secret marker without using it", function()
        local Logic = load()
        assert.is_nil(Logic.MarkerIndex(secret, isSecret))
        assert.equal(8, Logic.MarkerIndex(8, isSecret))
        assert.is_nil(Logic.MarkerIndex(0, isSecret))
        assert.is_nil(Logic.MarkerIndex(nil, isSecret))
        assert.is_nil(Logic.MarkerIndex(9, isSecret))
    end)

    it("Role treats a secret or unknown role as NONE", function()
        local Logic = load()
        assert.equal("NONE", Logic.Role(secret, isSecret))
        assert.equal("TANK", Logic.Role("TANK", isSecret))
        assert.equal("NONE", Logic.Role(nil, isSecret))
        assert.equal("NONE", Logic.Role("SOMETHING", isSecret))
    end)
end)

describe("Logic.Flag", function()
    it("accepts true and 1 (older APIs) and rejects nil, false and secrets (regression: 1 counted as no)", function()
        local Logic = load()
        local secret = {}
        local isSecret = function(value) return rawequal(value, secret) end
        assert.is_true(Logic.Flag(true, isSecret))
        assert.is_true(Logic.Flag(1, isSecret))
        assert.is_false(Logic.Flag(nil, isSecret))
        assert.is_false(Logic.Flag(false, isSecret))
        assert.is_false(Logic.Flag(secret, isSecret))
    end)
end)

describe("Collapse state", function()
    it("old saves get collapsed = false, a saved true stays, position and note survive", function()
        local Logic = load()
        local db = Logic.Migrate({ x = 5, y = 6, note = "Kara" })
        assert.is_false(db.collapsed)
        db = Logic.Migrate({ x = 5, collapsed = true, markers = { 8, 7, 5, 6, 4, 3, 2, 1 } })
        assert.is_true(db.collapsed)
        assert.equal(5, db.x)
    end)

    it("Restore Defaults expands the bar (documented) and keeps position and note", function()
        local db = load().RestoreDefaults({ collapsed = true, x = 5, note = "Kara" })
        assert.is_false(db.collapsed)
        assert.equal(5, db.x)
        assert.equal("Kara", db.note)
    end)
end)

describe("Window settings (panel opacity)", function()
    it("old saves get 75 %; a saved value stays; Restore Defaults resets it; an old snapWindows is ignored", function()
        local M = load()
        local db = M.Migrate({ x = 12, y = 34 })
        assert.equal(0.75, db.opacity)
        assert.equal(12, db.x)
        db = M.Migrate({ opacity = 0.4, snapWindows = false })
        assert.equal(0.4, db.opacity)
        db = M.RestoreDefaults({ opacity = 0.4, snapWindows = false, bindings = {}, bindingRanks = {}, watch = {} })
        assert.equal(0.75, db.opacity)
    end)
end)

describe("Logic.ValidMarkers and note type (audit 2026-11-08)", function()
    it("accepts empty slots and a full list, rejects duplicates, ranges and non-numbers", function()
        local Logic = load()
        assert.is_true(Logic.ValidMarkers({ 8, 7, 5, 6, 4, 3, 2, 1 }))
        assert.is_true(Logic.ValidMarkers({ 8, 0, 0, 6, 4, 0, 0, 1 }))
        assert.is_false(Logic.ValidMarkers({ 8, 8, 5, 6, 4, 3, 2, 1 }))
        assert.is_false(Logic.ValidMarkers({ 9, 7, 5, 6, 4, 3, 2, 1 }))
        assert.is_false(Logic.ValidMarkers({ 8, 7, 5, 6, 4, 3, 2, 1.5 }))
        assert.is_false(Logic.ValidMarkers({ 8, 7, 5, 6, 4, 3, 2, "1" }))
        assert.is_false(Logic.ValidMarkers("x"))
    end)

    it("Migrate replaces an invalid marker list and a non-text note", function()
        local db = load().Migrate({ markers = { 8, 8, 8, 8, 8, 8, 8, 8 }, note = 5 })
        assert.same({ 8, 7, 5, 6, 4, 3, 2, 1 }, db.markers)
        assert.equal("", db.note)
    end)

    it("CleanNote copes with non-text and keeps one string", function()
        local Logic = load()
        assert.equal("", Logic.CleanNote(nil))
        assert.equal("", Logic.CleanNote(12))
        assert.equal("a b", Logic.CleanNote("a\nb"))
    end)
end)

describe("sheep calls (owner 2026-11-18)", function()
    it("defaults to the moon and repairs a broken saved marker", function()
        local Logic = load()
        assert.equal(5, Logic.Migrate(nil).sheepMarker)
        assert.is_true(Logic.Migrate(nil).showSheep)
        assert.equal(8, Logic.Migrate({ sheepMarker = 8 }).sheepMarker)
        for _, broken in ipairs({ 0, 9, 2.5, "5", true }) do
            assert.equal(5, Logic.Migrate({ sheepMarker = broken }).sheepMarker)
        end
    end)

    it("marks only a living enemy target", function()
        assert.equal("/tm [@target,harm,nodead] 5", load().SheepMacroText(5))
    end)

    it("builds the chat line with the marker icon and the name when known", function()
        local Logic = load()
        assert.equal("Bitte schafen: {rt5} Kultist", Logic.SheepText("Bitte schafen: %s", 5, "Kultist"))
        assert.equal("Bitte nachschafen: {rt2}", Logic.SheepText("Bitte nachschafen: %s", 2, nil))
        assert.equal("Please sheep: {rt5}", Logic.SheepText("Please sheep: %s", 5, ""))
    end)

    it("sends to raid, party or nowhere", function()
        local Logic = load()
        assert.equal("RAID", Logic.ChatChannel({ inRaid = true, inGroup = true }))
        assert.equal("PARTY", Logic.ChatChannel({ inGroup = true }))
        assert.is_nil(Logic.ChatChannel({}))
    end)

    it("ignores a second call within the cooldown", function()
        local Logic = load()
        assert.is_true(Logic.CallReady(10, nil))
        assert.is_false(Logic.CallReady(11, 10))
        assert.is_true(Logic.CallReady(11.5, 10))
    end)
end)
